export type AppStringKey = keyof (typeof APP_STRINGS)['en'];
export type AnyKey = AppStringKey | StringKey;

export function translate(key: AnyKey, lang: Language): string {
  const app = APP_STRINGS[lang] as Record<string, string>;
  const core = STRINGS[lang] as Record<string, string>;
  return app[key] ?? core[key] ?? (APP_STRINGS.en as Record<string, string>)[key] ?? (STRINGS.en as Record<string, string>)[key] ?? key;
}

export function useStrings() {
  const lang = useSession((s) => s.language);
  return useCallback((key: AnyKey) => translate(key, lang), [lang]);
}
